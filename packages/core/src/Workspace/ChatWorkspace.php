    /** Host entry point for opening a chat in an already authenticated workspace. */
    public function open(CallContext $context, int $retentionSeconds = 86400): string
    {
        $revision = $this->policy->profile($context)->revision;
        if ($retentionSeconds < 1 || $revision === '' || mb_strlen($revision) > 128) {
            throw OfficeException::invalidInput();
        }

        return $this->db->transaction(function () use ($context, $revision, $retentionSeconds): string {
            $now = $this->db->clockNow($this->clock);
            $fields = [
                'tenant_id' => $context->tenantId,
                'project_scope' => $context->projectScope,
                'owner_subject' => $context->effectiveSubject,
                'profile_revision' => $revision,
                'retention_until' => $this->db->utcTimestamp($now->modify('+'.$retentionSeconds.' seconds')),
                'created_at' => $this->db->utcTimestamp($now),
                'updated_at' => $this->db->utcTimestamp($now),
            ];
            $query = $this->db->query('ai_chat_sessions');
            if ($this->db->driver() === 'pgsql') {
                // The PostgreSQL processor returns the UUID generated by RETURNING.
                return (string) $query->insertGetId($fields, 'session_id');
            }

            $id = $this->db->newUuid();
            $query->insert($fields + ['session_id' => $id]);

            return $id;
        }, $context->tenantId);
    }

    /**
     * @param  list<string>  $scope
     * @param  array<string, mixed>|null  $selection
     */
    public function post(CallContext $context, string $sessionId, string $messageId, string $content, array $scope, ?array $selection = null): string
    {
        [$scope, $normalizedSelection, $digest] = $this->prepareUserMessagePayload($messageId, $content, $scope, $selection);

        return $this->db->transaction(function () use ($context, $sessionId, $messageId, $content, $scope, $normalizedSelection, $digest): string {
            $session = $this->session($context, $sessionId, lock: true);
            if (! $this->canRead($scope, $this->accessible($context, $scope))) {
                throw OfficeException::resourceUnavailable();
            }

            $message = $this->db->query('ai_chat_messages')->where('session_id', $sessionId)->where('message_id', $messageId)->first();
            if ($message !== null) {
                $stored = $this->db->decodeBinary(QueryRecord::raw($message, 'content_digest'));
                if (! hash_equals($stored, $digest) || QueryRecord::str($message, 'role') !== 'user') {
                    throw new OfficeException(ErrorCode::IdempotencyConflict);
                }
                $run = $this->runs->find($context, QueryRecord::str($message, 'run_id')) ?? throw OfficeException::resourceUnavailable();
            } else {
                $revision = QueryRecord::str($session, 'profile_revision');
                if (QueryRecord::str($session, 'state') !== 'active' || $revision !== $this->policy->profile($context)->revision) {
                    throw OfficeException::preconditionFailed();
                }
                $now = $this->db->clockNow($this->clock);
                $until = $this->db->parseUtcTimestamp(QueryRecord::raw($session, 'retention_until'));
                $run = $this->runs->createOrFind(
                    $context,
                    'chat',
                    hash('sha256', $sessionId.':'.$messageId),
                    $revision,
                    ['session_id' => $sessionId, 'profile' => $context->profile],
                    max(1, ($until?->getTimestamp() ?? 0) - $now->getTimestamp()),
                );
                $this->insertMessage($context, $sessionId, $messageId, $run->runId, 'user', $content, $scope, $digest, $normalizedSelection);
                $this->sessionQuery($context, $sessionId)->update(['updated_at' => $this->db->utcTimestamp($now)]);
            }

            if (! in_array($run->state, ['completed', 'rejected', 'cancelled'], true)) {
                $this->dispatch($context, $run->runId);
            }

            return $run->runId;
        }, $context->tenantId);
    }

    /** @return array{sessions:list<array{session_id:string,state:string,last_seq:int}>, next_cursor:?string} */
    public function sessions(CallContext $context, ?string $cursor): array
    {
        if ($cursor !== null && (! Str::isUuid($cursor) || $cursor !== strtolower($cursor))) {
            throw OfficeException::invalidInput();
        }

        return $this->db->transaction(function () use ($context, $cursor): array {
            $query = $this->db->query('ai_chat_sessions')->where([
                'tenant_id' => $context->tenantId,
                'project_scope' => $context->projectScope,
                'owner_subject' => $context->effectiveSubject,
            ])->where('retention_until', '>', $this->db->utcTimestamp($this->db->clockNow($this->clock)));
            if ($cursor !== null) {
                $query->where('session_id', '<', $cursor);
            }
            $sessions = [];
            $rows = $query->orderByDesc('session_id')->limit(self::PAGE_SIZE + 1)->get();
            foreach ($rows->take(self::PAGE_SIZE) as $row) {
                $sessions[] = [
                    'session_id' => QueryRecord::str($row, 'session_id'),
                    'state' => QueryRecord::str($row, 'state'),
                    'last_seq' => QueryRecord::int($row, 'last_seq'),
                ];
            }

            return [
                'sessions' => $sessions,
                'next_cursor' => $rows->count() > self::PAGE_SIZE ? ($sessions[self::PAGE_SIZE - 1]['session_id'] ?? null) : null,
            ];
        }, $context->tenantId);
    }

    public function archive(CallContext $context, string $sessionId): void
    {
        $this->db->transaction(function () use ($context, $sessionId): void {
            $this->session($context, $sessionId, lock: true);
            $this->sessionQuery($context, $sessionId)->update(['state' => 'archived']);
        }, $context->tenantId);
    }

    public function cancel(CallContext $context, string $sessionId, string $runId): string
    {
        return $this->db->transaction(function () use ($context, $sessionId, $runId): string {
            $query = $this->ownedChatRun($context, $runId);
            if ($this->db->driver() !== 'pgsql') {
                (clone $query)->update(['cancel_requested' => $this->db->connection()->raw('cancel_requested')]);
            }
            $run = $query->lockForUpdate()->first() ?? throw OfficeException::resourceUnavailable();
            $this->session($context, $sessionId, lock: true);
            $scope = $this->storedScope($this->runMessage($sessionId, $runId) ?? throw OfficeException::resourceUnavailable());
            if (! $this->canRead($scope, $this->accessible($context, $scope))) {
                throw OfficeException::resourceUnavailable();
            }

            $state = QueryRecord::str($run, 'state');
            if (in_array($state, ['completed', 'rejected'], true)) {
                return QueryRecord::bool($run, 'cancel_requested') ? 'cancelled' : $state;
            }
            $now = $this->db->clockNow($this->clock);
            $fields = ['cancel_requested' => true, 'updated_at' => $this->db->utcTimestamp($now)];
            if ($this->db->parseUtcTimestamp(QueryRecord::raw($run, 'lease_until')) > $now) {
                $query->update($fields);

                return 'cancelling';
            }
            $query->update($fields + ['state' => 'rejected', 'lease_token' => null, 'lease_until' => null]);
            $this->append($context, $sessionId, $runId, 'run.finished', ['state' => 'cancelled', 'error' => null], $scope);

            return 'cancelled';
        }, $context->tenantId);
    }

    /** @phpstan-impure */
    public function cancellationRequested(CallContext $context, string $runId): bool
    {
        $read = fn (): bool => $this->ownedChatRun($context, $runId)->where('cancel_requested', true)->exists();

        // PostgreSQL tenant policies can depend on the transaction-local tenant setting.
        return $this->db->driver() === 'sqlite' ? $read() : $this->db->transaction($read, $context->tenantId);
    }

    public function retry(CallContext $context, string $sessionId, string $runId): string
    {
        return $this->db->transaction(function () use ($context, $sessionId, $runId): string {
            $session = $this->session($context, $sessionId, lock: true);
            $run = $this->runs->find($context, $runId) ?? throw OfficeException::resourceUnavailable();
            if ($run->channel !== 'chat' || ($run->input['session_id'] ?? null) !== $sessionId
                || ($run->input['profile'] ?? null) !== $context->profile) {
                throw OfficeException::resourceUnavailable();
            }
            if (! in_array($run->state, ['cancelled', 'rejected'], true)) {
                throw OfficeException::preconditionFailed();
            }
            $input = $this->turnInput($context, $sessionId, $runId);
            $source = $this->runMessage($sessionId, $runId) ?? throw OfficeException::resourceUnavailable();
            $now = $this->db->clockNow($this->clock);
            $until = $this->db->parseUtcTimestamp(QueryRecord::raw($session, 'retention_until'));
            $retry = $this->runs->createOrFind($context, 'chat', hash('sha256', 'retry:'.$runId),
                QueryRecord::str($session, 'profile_revision'),
                ['session_id' => $sessionId, 'profile' => $context->profile, 'retry_of' => $runId],
                max(1, ($until?->getTimestamp() ?? 0) - $now->getTimestamp()));
            if ($this->runMessage($sessionId, $retry->runId) === null) {
                $this->insertMessage($context, $sessionId, $this->db->newUuid(), $retry->runId, 'user',
                    $input['content'], $input['resource_ids'], $this->db->decodeBinary(QueryRecord::raw($source, 'content_digest')), $input['selection']);
                $this->sessionQuery($context, $sessionId)->update(['updated_at' => $this->db->utcTimestamp($now)]);
            }
            if (! in_array($retry->state, ['completed', 'rejected', 'cancelled'], true)) {
                $this->dispatch($context, $retry->runId);
            }

            return $retry->runId;
        }, $context->tenantId);
    }

    private function ownedChatRun(CallContext $context, string $runId): Builder
    {
        if (! Str::isUuid($runId) || $runId !== strtolower($runId)) {
            throw OfficeException::resourceUnavailable();
        }

        return $this->db->query('ai_runs')->useWritePdo()->where([
            'run_id' => $runId,
            'channel' => 'chat',
            'tenant_id' => $context->tenantId,
            'project_scope' => $context->projectScope,
            'effective_subject' => $context->effectiveSubject,
        ]);
    }

    private function dispatch(CallContext $context, string $runId): void
    {
        $this->db->afterCommit(function () use ($context, $runId): void {
            $this->dispatcher->dispatch(new ExecuteChatRun($context->tenantId, $runId));
        });
    }

    /**
     * Bind an already created external channel run (e.g. laravel-ai / agentools) into a chat session.
     *
     * @param  list<string>  $scope
     * @param  array<string, mixed>|null  $selection
     */
    public function linkExternalRunMessage(
        CallContext $context,
        string $sessionId,
        string $messageId,
        string $runId,
        string $content,
        array $scope,
        ?array $selection = null,
    ): void {
        [$scope, $normalizedSelection, $digest] = $this->prepareUserMessagePayload($messageId, $content, $scope, $selection);

        $this->db->transaction(function () use ($context, $sessionId, $messageId, $runId, $content, $scope, $normalizedSelection, $digest): void {
            $run = $this->runs->find($context, $runId) ?? throw OfficeException::resourceUnavailable();
            $resourceId = $run->input['resource_id'] ?? null;
            if ($run->channel === 'chat' || $run->sourceEventId !== $messageId || ! is_string($resourceId)
                || $scope !== [$resourceId] || ($run->input['chat_session_id'] ?? null) !== $sessionId) {
                throw new OfficeException(ErrorCode::IdempotencyConflict);
            }
            $session = $this->session($context, $sessionId, lock: true);
            if (! $this->canRead($scope, $this->accessible($context, $scope))) {
                throw OfficeException::resourceUnavailable();
            }

            $message = $this->db->query('ai_chat_messages')->where('session_id', $sessionId)->where('message_id', $messageId)->first();
            if ($message !== null) {
                $stored = $this->db->decodeBinary(QueryRecord::raw($message, 'content_digest'));
                if (! hash_equals($stored, $digest) || QueryRecord::str($message, 'role') !== 'user' || QueryRecord::str($message, 'run_id') !== $runId) {
                    throw new OfficeException(ErrorCode::IdempotencyConflict);
                }

                return;
            }

            if (QueryRecord::str($session, 'state') !== 'active') {
                throw OfficeException::preconditionFailed();
            }
            $this->insertMessage($context, $sessionId, $messageId, $runId, 'user', $content, $scope, $digest, $normalizedSelection);
            $now = $this->db->clockNow($this->clock);
            $this->sessionQuery($context, $sessionId)->update(['updated_at' => $this->db->utcTimestamp($now)]);
        }, $context->tenantId);
    }

    /**
     * Resolve the owning chat session and resource scope for a run linked to any chat message.
     *
     * @return array{session_id:string, scope:list<string>}|null
     */
    public function sessionBindingForRun(CallContext $context, string $runId): ?array
    {
        return $this->db->transaction(function () use ($context, $runId): ?array {
            $row = $this->db->query('ai_chat_messages')
                ->where('run_id', $runId)
                ->where('role', 'user')
                ->first();
            if ($row === null) {
                return null;
            }
            $sessionId = QueryRecord::str($row, 'session_id');
            $session = $this->sessionQuery($context, $sessionId)->first();
            if ($session === null || $this->expired($session)) {
                return null;
            }

            return [
                'session_id' => $sessionId,
                'scope' => $this->storedScope($row),
            ];
        }, $context->tenantId);
    }

    /**
     * @param  array<string, mixed>  $payload
     * @param  list<string>  $scope
     */
    public function appendOnceForRun(CallContext $context, string $sessionId, string $runId, string $type, array $payload, array $scope): ?int
    {
        $dedupeKey = hash('sha256', json_encode([
            $payload['call_id'] ?? null,
            $payload['proposal_id'] ?? null,
            $payload['state'] ?? null,
        ], JSON_THROW_ON_ERROR));

        return $this->db->transaction(function () use ($context, $sessionId, $runId, $type, $payload, $scope, $dedupeKey): ?int {
            $session = $this->session($context, $sessionId, lock: true);
            if ($this->runMessage($sessionId, $runId) === null) {
                throw OfficeException::resourceUnavailable();
            }

            $duplicate = $this->db->query('ai_chat_events')
                ->where('session_id', $sessionId)
                ->where('run_id', $runId)
                ->where('event_type', $type)
                ->where('dedupe_key', $dedupeKey)
                ->exists();
            if ($duplicate) {
                return null;
            }

            $seq = QueryRecord::int($session, 'last_seq') + 1;
            $aad = $this->aad($context, 'ai_chat_events', $sessionId, (string) $seq, $type, $scope);
            $encrypted = $this->cipher->encrypt($payload, $aad);
            $stamp = $this->db->utcTimestamp($this->db->clockNow($this->clock));
            $this->sessionQuery($context, $sessionId)->update(['last_seq' => $seq, 'updated_at' => $stamp]);
            $fields = [
                'session_id' => $sessionId,
                'seq' => $seq,
                'run_id' => $runId,
                'event_type' => $type,
                'resource_scope_json' => json_encode($scope, JSON_THROW_ON_ERROR),
                'key_id' => $encrypted['key_id'],
                'encrypted_payload' => $this->db->binaryLiteral($encrypted['ciphertext']),
                'dedupe_key' => $dedupeKey,
                'created_at' => $stamp,
            ];
            if ($this->db->driver() !== 'pgsql') {
                $fields['event_id'] = $this->db->newUuid();
            }
            $this->db->query('ai_chat_events')->insert($fields);
            $this->wakeup?->notify($sessionId);

            return $seq;
        }, $context->tenantId);
    }

    /**
     * @param  list<string>  $scope
     * @param  array<string, mixed>|null  $selection
     * @return array{0:list<string>, 1:?array<string,mixed>, 2:string}
     */
    private function prepareUserMessagePayload(string $messageId, string $content, array $scope, ?array $selection): array
    {
        if ($messageId === '' || strlen($messageId) > 255 || str_contains($messageId, "\0")
            || ! mb_check_encoding($messageId, 'UTF-8') || trim($content) === ''
            || strlen($content) > 65536 || ! mb_check_encoding($content, 'UTF-8') || count($scope) > 20) {
            throw OfficeException::invalidInput();
        }
        foreach ($scope as $id) {
            if ($id === '' || strlen($id) > 255 || str_contains($id, "\0") || ! mb_check_encoding($id, 'UTF-8')) {
                throw OfficeException::invalidInput();
            }
        }
        $scope = array_values(array_unique($scope));
        sort($scope, SORT_STRING);
        $normalizedSelection = $this->normalizeSelection($selection, $scope);
        $digestInput = ['content' => $content, 'resource_ids' => $scope];
        if ($normalizedSelection !== null) {
            $digestInput['selection'] = $normalizedSelection;
        }
        $canonicalInput = json_decode(
            json_encode($digestInput, JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES),
            false,
            512,
            JSON_THROW_ON_ERROR,
        );
        $digest = hash('sha256', ProposalDigest::canonicalize($canonicalInput), true);

        return [$scope, $normalizedSelection, $digest];
    }

    /** @return array{session_id:string, state:string, profile_revision:string, last_seq:int, provider:array{configured:bool, connection:string, driver:?string, model:?string, hint:?string}, runs:list<array<string,mixed>>, tool_calls:list<array<string,mixed>>, messages:list<array<string,mixed>>, next_before:?string, live_fragments:list<array{run_id:?string, seqs:list<int>, text:string, interrupted:bool, hidden:bool}>} */
    public function show(CallContext $context, string $sessionId, ?string $before = null): array
    {
        return $this->db->transaction(function () use ($context, $sessionId, $before): array {
            $session = $this->session($context, $sessionId);
            $lastSeq = QueryRecord::int($session, 'last_seq');
            $messages = [];
            $runsOut = [];
            $externalRuns = [];
            $callsOut = [];
            $profile = $this->policy->profile($context);

            $query = $this->db->query('ai_chat_messages')->where('session_id', $sessionId);
            if ($before !== null) {
                if (! $this->isValidBoundedToken($before, 255)) {
                    throw OfficeException::invalidInput();
                }
                $bookmark = (clone $query)->where('message_id', $before)->first(['created_at'])
                    ?? throw new OfficeException(ErrorCode::CursorExpired);
                $created = QueryRecord::str($bookmark, 'created_at');
                $query->where(static function (Builder $older) use ($created, $before): void {
                    $older->where('created_at', '<', $created)->orWhere(static function (Builder $sameTime) use ($created, $before): void {
                        $sameTime->where('created_at', $created)->where('message_id', '<', $before);
                    });
                });
            }
            $rows = $query->orderByDesc('created_at')->orderByDesc('message_id')->limit(self::PAGE_SIZE + 1)->get();
            $hasOlder = $rows->count() > self::PAGE_SIZE;
            $rows = $rows->take(self::PAGE_SIZE);
            $oldest = $rows->last();
            $allScopeIds = $this->collectScope($rows);
            $runIds = [];
            /** @var array<string, list<string>> $runScopeByRunId */
            $runScopeByRunId = [];
            foreach ($rows as $row) {
                $rid = QueryRecord::raw($row, 'run_id');
                if (is_string($rid) && $rid !== '') {
                    $runIds[$rid] = $rid;
                    if (QueryRecord::str($row, 'role') === 'user') {
                        $runScopeByRunId[$rid] = $this->storedScope($row);
                    }
                }
            }

            $callRows = $runIds === []
                ? []
                : $this->db->query('ai_tool_calls')
                    ->whereIn('run_id', array_values($runIds))
                    ->orderBy('run_id')
                    ->orderBy('step_id')
                    ->get()
                    ->all();
            $steps = [];
            foreach ($this->runs->listStepsByRunIdsInTransaction($context, array_values($runIds)) as $rid => $runSteps) {
                foreach ($runSteps as $step) {
                    $steps[$rid.':'.$step->stepId] = $step;
                    if ($step->resourceId !== null && $step->resourceId !== '') {
                        $allScopeIds[] = $step->resourceId;
                    }
                }
            }
            $allScopeIds = array_values(array_unique($allScopeIds));
            $allowed = $this->accessible($context, $allScopeIds);

            $completedAssistantRuns = [];
            foreach ($rows->reverse() as $row) {
                $scope = $this->storedScope($row);
                $id = QueryRecord::str($row, 'message_id');
                $role = QueryRecord::str($row, 'role');
                if ($role === 'assistant') {
                    $completedAssistantRuns[QueryRecord::str($row, 'run_id')] = true;
                }
                $decoded = $this->canRead($scope, $allowed) ? $this->messagePayload($context, $sessionId, $row, $scope) : null;
                if ($decoded === null) {
                    $messages[] = ['message_id' => $id, 'hidden' => true];

                    continue;
                }
                $item = [
                    'message_id' => $id,
                    'role' => $role,
                    'run_id' => QueryRecord::raw($row, 'run_id'),
                    'content' => $decoded['content'],
                ];
                if ($decoded['selection'] !== null) {
                    $item['selection'] = $decoded['selection'];
                }
                $messages[] = $item;
            }

            $runsById = $this->runs->findByIdsInTransaction($context, array_values($runIds));
            foreach (array_values($runIds) as $rid) {
                $run = $runsById[$rid] ?? null;
                if ($run !== null) {
                    if ($run->channel !== 'chat') {
                        $externalRuns[$rid] = $run->state;
                    }
                    $runsOut[] = [
                        'run_id' => $run->runId,
                        'state' => $run->state,
                        'channel' => $run->channel,
                        'created_at' => $run->createdAt->format('Y-m-d\TH:i:s\Z'),
                        'updated_at' => $run->updatedAt->format('Y-m-d\TH:i:s\Z'),
                    ];
                }
            }

            foreach ($callRows as $callRow) {
                $rid = QueryRecord::str($callRow, 'run_id');
                $cid = QueryRecord::str($callRow, 'call_id');
                $sid = QueryRecord::int($callRow, 'step_id');
                $step = $steps[$rid.':'.$sid] ?? null;
                $stepResource = $step?->resourceId;
                $requiredScope = $stepResource !== null && $stepResource !== ''
                    ? [$stepResource]
                    : ($runScopeByRunId[$rid] ?? []);
                if ($requiredScope !== [] && ! $this->canRead($requiredScope, $allowed)) {
                    $callsOut[] = [
                        'call_id' => $cid,
                        'run_id' => $rid,
                        'hidden' => true,
                    ];

                    continue;
                }
                $state = QueryRecord::str($callRow, 'state');
                $receiptId = QueryRecord::raw($callRow, 'receipt_id');
                $result = $step?->compactResult['result'] ?? null;
                $verification = $step?->compactResult['verification'] ?? null;
                $verificationFailed = $step?->operation === OfficeOperation::Commit && $state === 'committed' && is_array($verification);
                $receiptVerified = is_string($receiptId) && $state === 'verified' && (
                    $step?->operation === OfficeOperation::Commit
                    || ($step?->operation === OfficeOperation::Verify && is_array($result) && ($result['outcome'] ?? null) === 'passed')
                );
                $callsOut[] = [
                    'call_id' => $cid,
                    'run_id' => $rid,
                    'step_id' => $sid,
                    'tool' => QueryRecord::str($callRow, 'tool_name'),
                    'tool_version' => QueryRecord::str($callRow, 'tool_version'),
                    'state' => $state,
                    'resource_id' => $stepResource,
                    'proposal_id' => QueryRecord::raw($callRow, 'proposal_id'),
                    'command_id' => QueryRecord::raw($callRow, 'command_id'),
                    'receipt_id' => $receiptId,
                    'receipt_verified' => $receiptVerified,
                    'receipt_verification_failed' => $verificationFailed,
                ];
            }

            $provider = $this->secretStore !== null
                ? $this->withTenantSecretContext($context->tenantId, fn (): array => $this->secretStore->status($profile->providerConnection))
                : [
                    'configured' => false,
                    'connection' => $profile->providerConnection ?? '',
                    'driver' => null,
                    'model' => null,
                    'hint' => null,
                ];

            return [
                'session_id' => $sessionId,
                'state' => QueryRecord::str($session, 'state'),
                'profile_revision' => QueryRecord::str($session, 'profile_revision'),
                'last_seq' => $lastSeq,
                'provider' => $provider,
                'runs' => $runsOut,
                'tool_calls' => [...$callsOut, ...$this->externalToolCalls($context, $sessionId, $lastSeq, $externalRuns, $steps, $allowed)],
                'messages' => $messages,
                'next_before' => $hasOlder && $oldest !== null ? QueryRecord::str($oldest, 'message_id') : null,
                'live_fragments' => $this->liveFragments($context, $sessionId, $lastSeq, array_values($runIds), $completedAssistantRuns, $allowed),
            ];
        }, $context->tenantId);
    }

    /** @return array{content:string, resource_ids:list<string>, selection:?array<string,mixed>} */
    public function turnInput(CallContext $context, string $sessionId, string $runId): array
    {
        return $this->db->transaction(function () use ($context, $sessionId, $runId): array {
            $session = $this->session($context, $sessionId);
            if (QueryRecord::str($session, 'state') !== 'active'
                || QueryRecord::str($session, 'profile_revision') !== $this->policy->profile($context)->revision) {
                throw OfficeException::preconditionFailed();
            }
            $row = $this->runMessage($sessionId, $runId) ?? throw OfficeException::resourceUnavailable();
            $scope = $this->storedScope($row);
            if (! $this->canRead($scope, $this->accessible($context, $scope))) {
                throw OfficeException::resourceUnavailable();
            }

            $payload = $this->messagePayload($context, $sessionId, $row, $scope);

            return [
                'content' => $payload['content'],
                'resource_ids' => $scope,
                'selection' => $payload['selection'],
            ];
        }, $context->tenantId);
    }

    /** @param list<string> $scope */
    public function finishAssistantMessage(CallContext $context, string $sessionId, string $runId, string $content, array $scope): void
    {
        $this->db->transaction(function () use ($context, $sessionId, $runId, $content, $scope): void {
            $this->session($context, $sessionId, lock: true);
            if ($this->runMessage($sessionId, $runId) === null) {
                throw OfficeException::resourceUnavailable();
            }
            $this->insertMessage($context, $sessionId, $this->db->newUuid(), $runId, 'assistant', $content, $scope, hash('sha256', $content, true));
        }, $context->tenantId);
    }

    /**
     * @param  list<string>  $currentScope
     * @return list<array{role:string, content:string}>
     */
    public function history(CallContext $context, string $sessionId, string $runId, array $currentScope): array
    {
        return $this->db->transaction(function () use ($context, $sessionId, $runId, $currentScope): array {
            $this->session($context, $sessionId);
            $runs = $this->db->table('ai_runs');
            $priorRuns = $this->db->query('ai_chat_messages')->where('session_id', $sessionId)
                ->join($runs.' as history_run', 'history_run.run_id', '=', $this->db->table('ai_chat_messages').'.run_id')
                ->where('role', 'user')->where('history_run.run_id', '<', $runId)
                ->where('history_run.state', 'completed')->orderByDesc('history_run.run_id')->limit(self::HISTORY_TURNS)
                ->pluck('history_run.run_id');
            $rows = $this->db->query('ai_chat_messages')->where('session_id', $sessionId)
                ->whereIn('run_id', $priorRuns)->whereIn('role', ['user', 'assistant'])
                ->orderBy('run_id')->orderByDesc('role')->orderBy('created_at')->orderBy('message_id')->get();
            $allowed = $this->accessible($context, $currentScope);
            $turns = [];
            foreach ($rows as $row) {
                $turns[QueryRecord::str($row, 'run_id')][] = $row;
            }
            $history = [];
            $bytesLeft = self::HISTORY_BYTES;
            foreach (array_reverse($turns) as $turn) {
                $messages = [];
                $bytes = 0;
                foreach ($turn as $row) {
                    $scope = $this->storedScope($row);
                    if (array_diff($scope, $currentScope) !== [] || ! $this->canRead($scope, $allowed)) {
                        continue 2;
                    }
                    $message = $this->messagePayload($context, $sessionId, $row, $scope);
                    $messages[] = ['role' => QueryRecord::str($row, 'role'), 'content' => $message['content']];
                    $bytes += strlen($message['content']);
                }
                if ($bytes > $bytesLeft) {
                    break;
                }
                $bytesLeft -= $bytes;
                $history = [...$messages, ...$history];
            }

            return $history;
        }, $context->tenantId);
    }

    /**
     * @param  array<string,mixed>  $payload
     * @param  list<string>  $scope
     */
    public function append(CallContext $context, string $sessionId, ?string $runId, string $type, array $payload, array $scope): int
    {
        return $this->db->transaction(function () use ($context, $sessionId, $runId, $type, $payload, $scope): int {
            $session = $this->session($context, $sessionId, lock: true);
            if ($runId !== null && $this->runMessage($sessionId, $runId) === null) {
                throw OfficeException::resourceUnavailable();
            }
            $seq = QueryRecord::int($session, 'last_seq') + 1;
            $aad = $this->aad($context, 'ai_chat_events', $sessionId, (string) $seq, $type, $scope);
            $encrypted = $this->cipher->encrypt($payload, $aad);
            $stamp = $this->db->utcTimestamp($this->db->clockNow($this->clock));
            $this->sessionQuery($context, $sessionId)->update(['last_seq' => $seq, 'updated_at' => $stamp]);
            $fields = [
                'session_id' => $sessionId,
                'seq' => $seq,
                'run_id' => $runId,
                'event_type' => $type,
                'resource_scope_json' => json_encode($scope, JSON_THROW_ON_ERROR),
                'key_id' => $encrypted['key_id'],
                'encrypted_payload' => $this->db->binaryLiteral($encrypted['ciphertext']),
                'created_at' => $stamp,
            ];
            if ($this->db->driver() !== 'pgsql') {
                $fields['event_id'] = $this->db->newUuid();
            }
            $this->db->query('ai_chat_events')->insert($fields);
            $this->wakeup?->notify($sessionId);

            return $seq;
        }, $context->tenantId);
    }

    /** @return list<array{seq:int, type:string, data:array<string,mixed>}> */
    public function events(CallContext $context, string $sessionId, int $cursor): array
    {
        return $this->db->transaction(function () use ($context, $sessionId, $cursor): array {
            $session = $this->session($context, $sessionId);
            $rows = $this->db->query('ai_chat_events')->useWritePdo()->where('session_id', $sessionId)
                ->where('seq', '>', $cursor)->orderBy('seq')->limit(self::PAGE_SIZE)->get();
            if ($cursor > QueryRecord::int($session, 'last_seq') || ($rows->isEmpty() && $cursor < QueryRecord::int($session, 'last_seq'))) {
                throw new OfficeException(ErrorCode::CursorExpired);
            }

            $allowed = $this->accessible($context, $this->collectScope($rows));
            $events = [];
            foreach ($rows as $row) {
                $seq = QueryRecord::int($row, 'seq');
                if ($seq !== ++$cursor) {
                    throw new OfficeException(ErrorCode::CursorExpired);
                }
                $scope = $this->storedScope($row);
                if (! $this->canRead($scope, $allowed)) {
                    $events[] = ['seq' => $seq, 'type' => 'hidden', 'data' => []];

                    continue;
                }
                $type = QueryRecord::str($row, 'event_type');
                $data = $this->eventPayload($context, $sessionId, $row, $seq, $type, $scope);
                $events[] = ['seq' => $seq, 'type' => $type, 'data' => ['run_id' => QueryRecord::raw($row, 'run_id')] + $data];
            }

            return $events;
        }, $context->tenantId);
    }

    /**
     * @param  list<string>  $runIds
     * @param  array<string, true>  $completedAssistantRuns
     * @param  array<string, ResourceEntry>  $allowed
     * @return list<array{run_id:?string, seqs:list<int>, text:string, interrupted:bool, hidden:bool}>
     */
    private function liveFragments(CallContext $context, string $sessionId, int $lastSeq, array $runIds, array $completedAssistantRuns, array $allowed): array
    {
        $rows = $this->db->query('ai_chat_events')->useWritePdo()->where('session_id', $sessionId)
            ->whereIn('run_id', $runIds)->where('seq', '<=', $lastSeq)
            ->where(static function (Builder $query) use ($completedAssistantRuns): void {
                $query->where('event_type', 'assistant.interrupted')
                    ->orWhere(static function (Builder $deltas) use ($completedAssistantRuns): void {
                        $deltas->where('event_type', 'assistant.delta')
                            ->whereNotIn('run_id', array_keys($completedAssistantRuns));
                    });
            })->orderByDesc('seq')->limit(self::SNAPSHOT_EVENTS)->get()->reverse();
        $fragments = [];
        $fragment = null;
        foreach ($rows as $row) {
            $runId = QueryRecord::str($row, 'run_id');
            $seq = QueryRecord::int($row, 'seq');
            $scope = $this->storedScope($row);
            $type = QueryRecord::str($row, 'event_type');
            $hidden = ! $this->canRead($scope, $allowed);
            $text = '';
            if (! $hidden && $type === 'assistant.delta') {
                $data = $this->eventPayload($context, $sessionId, $row, $seq, $type, $scope);
                $text = is_string($data['text'] ?? null) ? $data['text'] : '';
            }
            if ($fragment === null || $fragment['run_id'] !== $runId || $fragment['hidden'] !== $hidden
                || ($fragment['interrupted'] && $type === 'assistant.delta')) {
                if ($fragment !== null) {
                    $fragments[] = $fragment;
                }
                $fragment = ['run_id' => $runId, 'seqs' => [], 'text' => '', 'interrupted' => false, 'hidden' => $hidden];
            }
            $fragment['seqs'][] = $seq;
            $fragment['text'] .= $text;
            $fragment['interrupted'] = ! $hidden && $type === 'assistant.interrupted';
        }
        if ($fragment !== null) {
            $fragments[] = $fragment;
        }

        return array_map(static function (array $fragment): array {
            if ($fragment['hidden']) {
                $fragment['run_id'] = null;
            }

            return $fragment;
        }, $fragments);
    }

    /**
     * @param  array<string, string>  $runStates
     * @param  array<string, OfficeRunStep>  $steps
     * @param  array<string, ResourceEntry>  $allowed
     * @return list<array<string, mixed>>
     */
    private function externalToolCalls(CallContext $context, string $sessionId, int $lastSeq, array $runStates, array $steps, array $allowed): array
    {
        if ($runStates === []) {
            return [];
        }

        $stepsByCall = [];
        foreach ($steps as $step) {
            $stepsByCall['ext-step-'.$step->runId.'-'.$step->stepId] = $step;
        }
        $rows = $this->db->query('ai_chat_events')->useWritePdo()->where('session_id', $sessionId)
            ->whereIn('run_id', array_keys($runStates))->where('seq', '<=', $lastSeq)
            ->whereIn('event_type', ['tool.requested', 'approval.required', 'tool.committed', 'tool.verified'])
            ->orderByDesc('seq')->limit(self::SNAPSHOT_EVENTS)->get()->reverse();
        $calls = [];
        $settledProposals = [];
        foreach ($rows as $row) {
            $runId = QueryRecord::str($row, 'run_id');
            $scope = $this->storedScope($row);
            if (! $this->canRead($scope, $allowed)) {
                $hiddenId = 'hidden-external-'.$runId;
                $calls[$hiddenId] = ['call_id' => $hiddenId, 'run_id' => $runId, 'hidden' => true];

                continue;
            }
            $type = QueryRecord::str($row, 'event_type');
            $data = $this->eventPayload($context, $sessionId, $row, QueryRecord::int($row, 'seq'), $type, $scope);
            $callId = $data['call_id'] ?? null;
            $step = is_string($callId) ? ($stepsByCall[$callId] ?? null) : null;
            if (! is_string($callId) || $step === null) {
                continue;
            }
            $call = $calls[$callId] ?? [
                'call_id' => $callId, 'run_id' => $runId, 'step_id' => $step->stepId,
                'tool' => $step->operation->value, 'tool_version' => '1', 'resource_id' => $step->resourceId,
                'proposal_id' => null, 'command_id' => null, 'receipt_id' => null, 'receipt_verified' => false,
            ];
            $verification = is_array($data['verification'] ?? null) ? $data['verification'] : [];
            $result = is_array($verification['result'] ?? null) ? $verification['result'] : [];
            $verified = ($verification['ok'] ?? null) === true && ($result['outcome'] ?? null) === 'passed'
                && is_string($data['receipt_id'] ?? null);
            $call['state'] = match ($type) {
                'approval.required' => 'awaiting_approval',
                'tool.committed' => 'committed',
                'tool.verified' => $verified ? 'verified' : 'committed',
                default => 'requested',
            };
            foreach (['proposal_id', 'command_id', 'receipt_id'] as $field) {
                if (is_string($data[$field] ?? null)) {
                    $call[$field] = $data[$field];
                }
            }
            $call['receipt_verified'] = $verified;
            $call['receipt_verification_failed'] = $type === 'tool.verified' && ! $verified;
            $proposalId = $call['proposal_id'] ?? null;
            if (is_string($proposalId) && is_string($call['receipt_id'] ?? null)) {
                $settledProposals[$proposalId] = true;
            }
            $calls[$callId] = $call;
        }

        foreach ($calls as &$call) {
            $proposalId = $call['proposal_id'] ?? null;
            if (($call['state'] ?? null) === 'awaiting_approval'
                && ((is_string($proposalId) && isset($settledProposals[$proposalId]))
                    || ($runStates[$call['run_id']] ?? null) === 'rejected')) {
                $call['state'] = 'finished';
            }
        }
        unset($call);

        return array_values($calls);
    }

    /** @param list<string> $scope
     * @return array<string, mixed>
     */
    private function eventPayload(CallContext $context, string $sessionId, object $row, int $seq, string $type, array $scope): array
    {
        $key = QueryRecord::raw($row, 'key_id');

        return is_string($key) ? $this->cipher->decrypt(
            $key,
            $this->db->decodeBinary(QueryRecord::raw($row, 'encrypted_payload')),
            $this->aad($context, 'ai_chat_events', $sessionId, (string) $seq, $type, $scope),
        ) : [];
    }

    private function session(CallContext $context, string $sessionId, bool $lock = false): object
    {
        if (! Str::isUuid($sessionId) || strtolower($sessionId) !== $sessionId) {
            throw OfficeException::resourceUnavailable();
        }
        $query = $this->sessionQuery($context, $sessionId)->useWritePdo();
        if ($lock) {
            if ($this->db->driver() === 'pgsql') {
                $query->lockForUpdate();
            } else {
                // SQLite takes its write lock before the transaction reads a snapshot.
                (clone $query)->increment('last_seq', 0);
            }
        }
        $row = $query->first() ?? throw OfficeException::resourceUnavailable();
        if ($this->expired($row)) {
            throw new OfficeException(ErrorCode::CursorExpired);
        }

        return $row;
    }

    private function expired(object $row): bool
    {
        $expiry = $this->db->parseUtcTimestamp(QueryRecord::raw($row, 'retention_until'));

        return $expiry === null || $expiry <= $this->db->clockNow($this->clock);
    }

    private function sessionQuery(CallContext $context, string $sessionId): Builder
    {
        return $this->db->query('ai_chat_sessions')->where([
            'session_id' => $sessionId,
            'tenant_id' => $context->tenantId,
            'project_scope' => $context->projectScope,
            'owner_subject' => $context->effectiveSubject,
        ]);
    }

    /**
     * @template T
     *
     * @param  callable(): T  $callback
     * @return T
     */
    private function withTenantSecretContext(string $tenantId, callable $callback): mixed
    {
        $hadPrior = Context::has('vaulter.ai.tenant_id');
        $prior = $hadPrior ? Context::get('vaulter.ai.tenant_id') : null;
        Context::add('vaulter.ai.tenant_id', $tenantId);

        try {
            return $callback();
        } finally {
            if ($hadPrior) {
                Context::add('vaulter.ai.tenant_id', $prior);
            } else {
                Context::forget(['vaulter.ai.tenant_id']);
            }
        }
    }

    private function runMessage(string $sessionId, string $runId): ?object
    {
        return $this->db->query('ai_chat_messages')->where([
            'session_id' => $sessionId, 'run_id' => $runId, 'role' => 'user',
        ])->first();
    }

    /**
     * @param  list<string>  $scope
     * @param  array<string, mixed>|null  $selection
     */
    private function insertMessage(
        CallContext $context,
        string $sessionId,
        string $messageId,
        string $runId,
        string $role,
        string $body,
        array $scope,
        string $digest,
        ?array $selection = null,
    ): void {
        $aad = $this->aad($context, 'ai_chat_messages', $sessionId, $messageId, $role, $scope);
        $plain = ['content' => $body];
        if ($selection !== null) {
            $plain['selection'] = $selection;
        }
        $encrypted = $this->cipher->encrypt($plain, $aad);
        $this->db->query('ai_chat_messages')->insert([
            'session_id' => $sessionId,
            'message_id' => $messageId,
            'run_id' => $runId,
            'role' => $role,
            'author_subject' => $role === 'user' ? $context->effectiveSubject : null,
            'content_digest' => $this->db->binaryLiteral($digest),
            'resource_scope_json' => json_encode($scope, JSON_THROW_ON_ERROR),
            'key_id' => $encrypted['key_id'],
            'encrypted_body' => $this->db->binaryLiteral($encrypted['ciphertext']),
            'created_at' => $this->db->utcTimestamp($this->db->clockNow($this->clock)),
        ]);
    }

    /**
     * @param  list<string>  $scope
     * @return array{content:string, selection:?array<string, mixed>}
     */
    private function messagePayload(CallContext $context, string $sessionId, object $row, array $scope): array
    {
        $body = $this->cipher->decrypt(
            QueryRecord::str($row, 'key_id'),
            $this->db->decodeBinary(QueryRecord::raw($row, 'encrypted_body')),
            $this->aad($context, 'ai_chat_messages', $sessionId, QueryRecord::str($row, 'message_id'), QueryRecord::str($row, 'role'), $scope),
        );
        $content = $body['content'] ?? null;
        if (! is_string($content)) {
            throw new RuntimeException('Malformed chat message.');
        }

        $selection = null;
        if (is_array($body['selection'] ?? null)) {
            /** @var array<string, mixed> $typedSelection */
            $typedSelection = $body['selection'];
            $selection = $typedSelection;
        }

        return ['content' => $content, 'selection' => $selection];
    }

    /**
     * @param  array<string, mixed>|null  $selection
     * @param  list<string>  $scope
     * @return array<string, mixed>|null
     */
    private function normalizeSelection(?array $selection, array $scope): ?array
    {
        if ($selection === null) {
            return null;
        }

        $kind = $selection['kind'] ?? null;
        $resourceId = $selection['resource_id'] ?? null;
        if (! is_string($kind) || ! is_string($resourceId) || ! $this->isValidBoundedToken($resourceId, 255)
            || ! in_array($resourceId, $scope, true)) {
            throw OfficeException::invalidInput();
        }

        if ($kind === 'text_block') {
            $allowedKeys = ['kind', 'resource_id', 'block_id', 'excerpt', 'start_utf16', 'end_utf16'];
            if (array_diff(array_keys($selection), $allowedKeys) !== []) {
                throw OfficeException::invalidInput();
            }
            $blockId = $selection['block_id'] ?? null;
            if (! is_string($blockId) || ! $this->isValidBoundedToken($blockId, self::MAX_SELECTION_ID_BYTES)) {
                throw OfficeException::invalidInput();
            }

            $normalized = [
                'kind' => 'text_block',
                'resource_id' => $resourceId,
                'block_id' => $blockId,
            ];

            if (array_key_exists('excerpt', $selection) && $selection['excerpt'] !== null) {
                $excerpt = $selection['excerpt'];
                if (! is_string($excerpt) || strlen($excerpt) > self::MAX_SELECTION_EXCERPT_BYTES
                    || str_contains($excerpt, "\0") || ! mb_check_encoding($excerpt, 'UTF-8')) {
                    throw OfficeException::invalidInput();
                }
                $normalized['excerpt'] = $excerpt;
            }

            $start = $selection['start_utf16'] ?? null;
            $end = $selection['end_utf16'] ?? null;
            if ($start !== null || $end !== null) {
                if (! is_int($start) || ! is_int($end) || $start < 0 || $end < $start
                    || ($end - $start) > self::MAX_SELECTION_EXCERPT_BYTES) {
                    throw OfficeException::invalidInput();
                }
                $normalized['start_utf16'] = $start;
                $normalized['end_utf16'] = $end;
            }

            return $normalized;
        }

        if ($kind === 'sheet_range') {
            $allowedKeys = ['kind', 'resource_id', 'sheet_id', 'table_id', 'row_ids', 'columns'];
            if (array_diff(array_keys($selection), $allowedKeys) !== []) {
                throw OfficeException::invalidInput();
            }
            $sheetId = $selection['sheet_id'] ?? null;
            $tableId = $selection['table_id'] ?? null;
            if (! is_string($sheetId) || ! $this->isValidBoundedToken($sheetId, self::MAX_SELECTION_ID_BYTES)
                || ! is_string($tableId) || ! $this->isValidBoundedToken($tableId, self::MAX_SELECTION_ID_BYTES)) {
                throw OfficeException::invalidInput();
            }

            $normalized = [
                'kind' => 'sheet_range',
                'resource_id' => $resourceId,
                'sheet_id' => $sheetId,
                'table_id' => $tableId,
            ];

            foreach (['row_ids', 'columns'] as $listKey) {
                if (array_key_exists($listKey, $selection) && $selection[$listKey] !== null) {
                    $list = $selection[$listKey];
                    if (! is_array($list) || ! array_is_list($list) || count($list) > self::MAX_SELECTION_ITEMS) {
                        throw OfficeException::invalidInput();
                    }
                    $items = [];
                    foreach ($list as $item) {
                        if (! is_string($item) || ! $this->isValidBoundedToken($item, self::MAX_SELECTION_ID_BYTES)) {
                            throw OfficeException::invalidInput();
                        }
                        $items[] = $item;
                    }
                    $normalized[$listKey] = $items;
                }
            }

            return $normalized;
        }

        throw OfficeException::invalidInput();
    }

    private function isValidBoundedToken(string $value, int $maxBytes): bool
    {
        return $value !== '' && strlen($value) <= $maxBytes
            && ! str_contains($value, "\0") && mb_check_encoding($value, 'UTF-8');
    }

    /** @return list<string> */
    private function storedScope(object $row): array
    {
        $scope = json_decode(QueryRecord::str($row, 'resource_scope_json'), false, 512, JSON_THROW_ON_ERROR);
        if (! is_array($scope) || ! array_is_list($scope) || array_filter($scope, is_string(...)) !== $scope) {
            throw new RuntimeException('Malformed chat resource scope.');
        }

        return $scope;
    }

    /** @param iterable<object> $rows
     * @return list<string>
     */
    private function collectScope(iterable $rows): array
    {
        $scope = [];
        foreach ($rows as $row) {
            foreach ($this->storedScope($row) as $id) {
                $scope[$id] = $id;
            }
        }

        return array_values($scope);
    }

    /** @param list<string> $scope
     * @return array<string, ResourceEntry>
     */
    private function accessible(CallContext $context, array $scope): array
    {
        return $scope === [] ? [] : $this->resources->filterAccessible($context, $scope);
    }

    /** @param list<string> $scope
     * @param  array<string, ResourceEntry>  $allowed
     */
    private function canRead(array $scope, array $allowed): bool
    {
        return array_diff_key(array_fill_keys($scope, true), $allowed) === [];
    }

    /** @param list<string> $scope
     * @return list<string>
     */
    private function aad(CallContext $context, string $table, string $sessionId, string $id, string $type, array $scope): array
    {
        return [$table, $context->tenantId, $context->projectScope, $context->effectiveSubject, $sessionId, $id, $type, ...$scope];
    }
